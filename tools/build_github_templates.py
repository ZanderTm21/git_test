"""Embed editor/github-template/* into editor/github_templates.php so the editor doesn't depend on that folder
(some file managers skip dot-folders like .github when extracting zips).

    python3 tools/build_github_templates.py
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TPL = ROOT / "editor" / "github-template"
FILES = [".github/workflows/site-edit.yml", "CLAUDE.md", "tools/edit_image.py", "tools/run_python.sh", ".gitignore"]

lines = ["<?php", "// Generated by tools/build_github_templates.py from editor/github-template/. Do not edit by hand.", "return ["]
for f in FILES:
    data = (TPL / f).read_bytes()
    assert data, f"{f} is empty"
    lines.append(f"    '{f}' => '{base64.b64encode(data).decode()}',")
lines.append("];")
(ROOT / "editor" / "github_templates.php").write_text("\n".join(lines) + "\n")
print("wrote editor/github_templates.php")
